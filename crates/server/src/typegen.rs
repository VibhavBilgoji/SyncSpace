//! TypeScript generation for the web app (`docs/API.md` section 4, task 1.4).
//!
//! [`generate`] writes one `.ts` file per wire type plus an `index.ts` into a directory, normally
//! `apps/web/src/types/generated/`. The files are committed. Three things keep them honest:
//!
//! - the directory is emptied of `*.ts` files first, so the folder holds exactly what the code
//!   exports and a removed or renamed type leaves nothing behind;
//! - a test generates into a temporary directory and compares it with the committed files, and CI
//!   regenerates and fails on any difference;
//! - no type uses `#[ts(export)]`, which would make `cargo test` write files as a side effect.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use crate::api_types::{
    ApiErrorBody, ApiErrorResponse, AuditEntry, Block, BlockType, Board, ChangeType, Document,
    DocumentSummary, ErrorCode, Page, Priority, Status, StatusCounts, Task, UserRef,
    VersionSummary,
};
use crate::auth::handlers::UserResponse;
use crate::auth::validation::{LoginInput, RegisterInput};
use crate::rbac::Role;
use crate::workspaces::handlers::{MemberResponse, SummaryResponse, WorkspaceResponse};
use crate::workspaces::validation::{AddMemberInput, CreateInput, PatchInput, RoleInput};

/// The first line of `index.ts`; the other files carry the header ts-rs writes.
const INDEX_HEADER: &str = "// Generated by `cargo run -p server --bin gen-types`. Do not edit.\n";

/// Where the web app expects the generated files, independent of the current directory.
pub fn default_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/web/src/types/generated")
}

/// Writes every exported type into `dir` and returns their names, sorted.
pub fn generate(dir: &Path) -> Result<Vec<String>, Box<dyn Error>> {
    fs::create_dir_all(dir)?;
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            fs::remove_file(path)?;
        }
    }

    // `i64` and `u64` fields (revision, counts) stay far below 2^53, so plain numbers do.
    let config = Config::new().with_out_dir(dir).with_large_int("number");
    export_all(&config)?;

    let mut names: Vec<String> = Vec::new();
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts")
            && let Some(stem) = path.file_stem().and_then(|stem| stem.to_str())
            && stem != "index"
        {
            names.push(stem.to_string());
        }
    }
    names.sort();

    let mut index = String::from(INDEX_HEADER);
    for name in &names {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    fs::write(dir.join("index.ts"), index)?;
    Ok(names)
}

/// The list of exported types. A type that is not named here is not in the contract.
fn export_all(config: &Config) -> Result<(), Box<dyn Error>> {
    // Types that have handlers (and the request bodies).
    Role::export_all(config)?;
    UserResponse::export_all(config)?;
    RegisterInput::export_all(config)?;
    LoginInput::export_all(config)?;
    WorkspaceResponse::export_all(config)?;
    SummaryResponse::export_all(config)?;
    MemberResponse::export_all(config)?;
    CreateInput::export_all(config)?;
    PatchInput::export_all(config)?;
    AddMemberInput::export_all(config)?;
    RoleInput::export_all(config)?;
    // Types of endpoints that come later (`api_types`).
    BlockType::export_all(config)?;
    Block::export_all(config)?;
    Status::export_all(config)?;
    Priority::export_all(config)?;
    ChangeType::export_all(config)?;
    UserRef::export_all(config)?;
    DocumentSummary::export_all(config)?;
    Document::export_all(config)?;
    VersionSummary::export_all(config)?;
    StatusCounts::export_all(config)?;
    Board::export_all(config)?;
    Task::export_all(config)?;
    AuditEntry::export_all(config)?;
    Page::<Task>::export_all(config)?;
    ErrorCode::export_all(config)?;
    ApiErrorBody::export_all(config)?;
    ApiErrorResponse::export_all(config)?;
    Ok(())
}
